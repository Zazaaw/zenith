import Foundation

/// Zenith fork: the Emoji Picker's decisions. Reading the bundled list (and
/// that it is Unicode's, with no images), which emoji a macOS draws, search
/// and ranking, skin tones, the recent and frequently used lists, the grid's
/// arrow keys and the preferences. No panel, no paste, no hotkey.
enum EmojiPickerTests {
    static func run(_ suite: TestSuite) {
        bundledList(suite)
        parsing(suite)
        versions(suite)
        search(suite)
        tones(suite)
        usage(suite)
        sections(suite)
        navigation(suite)
        preferences(suite)
    }

    private static let listPath = "Resources/Emoji/emoji.tsv"

    private static var bundled: [EmojiRecord] {
        guard let text = try? String(contentsOfFile: listPath, encoding: .utf8) else { return [] }
        return EmojiCatalog.parse(text)
    }

    private static func record(_ emoji: String, _ name: String, keywords: [String] = [], category: EmojiCategory = .smileys,
                               version: Double = 1, tone: String? = nil) -> EmojiRecord {
        EmojiRecord(category: category, emoji: emoji, name: name, keywords: keywords, version: version, toneTemplate: tone)
    }

    // MARK: The list

    private static func bundledList(_ suite: TestSuite) {
        let records = bundled
        suite.expect(records.count > 1800, "the bundled list holds Unicode's emoji (\(records.count))")
        suite.expect(Set(records.map(\.emoji)).count == records.count, "each emoji is listed once")
        suite.expect(Set(records.map(\.category)) == Set(EmojiCategory.allCases), "every category has emoji")
        suite.expect(records.first?.emoji == "😀" && records.first?.name == "grinning face",
                     "the list keeps Unicode's order, grinning face first")
        suite.expect(!records.contains { $0.emoji.unicodeScalars.contains { (0x1F3FB...0x1F3FF).contains($0.value) } },
                     "skin-tone variants are not listed on their own")
        let wave = records.first { $0.emoji == "👋" }
        suite.expect(wave?.toneTemplate == "👋🏻" && wave?.keywords.contains("hello") == true,
                     "an emoji that takes a tone carries its template and CLDR's keywords")
        suite.expect(records.first { $0.emoji == "😂" }?.keywords.contains("lol") == true, "😂 is found by lol")
        let text = (try? String(contentsOfFile: listPath, encoding: .utf8)) ?? ""
        suite.expect(text.hasPrefix("# Zenith Emoji Picker: generated by Tools/zenith-emoji-data.py")
                        && text.contains("Unicode License v3"),
                     "the list names its script and Unicode's licence")
        let notice = (try? String(contentsOfFile: "Resources/Emoji/NOTICE.txt", encoding: .utf8)) ?? ""
        suite.expect(notice.contains("UNICODE LICENSE V3") && notice.contains("Copyright © 1991-2026 Unicode, Inc."),
                     "the notice carries the Unicode licence in full")
        let folder = (try? FileManager.default.contentsOfDirectory(atPath: "Resources/Emoji")) ?? []
        suite.expect(Set(folder) == ["emoji.tsv", "NOTICE.txt"], "no emoji images are shipped: \(folder.sorted())")
        suite.expect(FileManager.default.fileExists(atPath: "Tools/zenith-emoji-data.py"), "the script that builds it is kept")
    }

    private static func parsing(_ suite: TestSuite) {
        let text = """
        # a comment
        smileys\t😀\tgrinning face\thappy|smile\t1.0\t
        people\t👋\twaving hand\thello|bye\t0.6\t👋🏻
        unknown\t🙂\tslightly smiling face\t\t1.0\t
        smileys\t\tempty\t\t1.0\t
        smileys\t🫨\tshaking face\tearthquake\tnot a number\t
        flags\t🇮🇩\tflag: Indonesia\t\t2.0
        """
        let records = EmojiCatalog.parse(text)
        suite.expect(records.map(\.emoji) == ["😀", "👋", "🇮🇩"],
                     "lines with an unknown group, no emoji or no version are skipped: \(records.map(\.emoji))")
        suite.expect(records.first?.keywords == ["happy", "smile"] && records.first?.toneTemplate == nil,
                     "keywords split on |, no template when the field is empty")
        suite.expect(records.last?.toneTemplate == nil && records.last?.category == .flags,
                     "a line without the template field still reads")
        suite.expect(EmojiCatalog.parse(text, maximumVersion: 1.0).map(\.emoji) == ["😀", "👋"],
                     "emoji newer than the Mac's font are left out")
    }

    private static func versions(_ suite: TestSuite) {
        func os(_ major: Int, _ minor: Int) -> OperatingSystemVersion {
            OperatingSystemVersion(majorVersion: major, minorVersion: minor, patchVersion: 0)
        }
        let cases: [(OperatingSystemVersion, Double)] = [
            (os(14, 0), 15.0), (os(14, 4), 15.1), (os(15, 3), 15.1), (os(15, 4), 16.0), (os(26, 0), 16.0),
            (os(26, 4), 17.0), (os(27, 2), 17.0), (os(27, 4), 18.0), (os(28, 0), 18.0),
        ]
        for (version, expected) in cases {
            suite.expect(EmojiCatalog.maximumVersion(for: version) == expected,
                         "macOS \(version.majorVersion).\(version.minorVersion) draws Emoji \(expected)")
        }
        let records = bundled
        let newest = records.map(\.version).max() ?? 0
        suite.expect(newest >= 17, "the list reaches the newest emoji (\(newest)), the Mac filters them")
    }

    // MARK: Search

    private static func search(_ suite: TestSuite) {
        let records = bundled
        func top(_ query: String, _ count: Int = 1) -> [String] {
            EmojiSearch.rank(records, query: query).prefix(count).map(\.emoji)
        }
        suite.expect(top("cat", 2) == ["🐈", "🐱"], "\"cat\" finds the cat, then its face: \(top("cat", 3))")
        suite.expect(top("thumbs up") == ["👍"], "two words find thumbs up: \(top("thumbs up", 3))")
        suite.expect((top("lol", 20).firstIndex(of: "😂") ?? 99) < (top("lol", 20).firstIndex(of: "🍭") ?? 100),
                     "a keyword finds 😂, before a name that only starts the same: \(top("lol", 8))")
        suite.expect(top("red heart") == ["❤️"], "\"red heart\": \(top("red heart", 3))")
        suite.expect(top("indonesia") == ["🇮🇩"], "a flag by its country: \(top("indonesia", 3))")
        suite.expect(top("ROCKET") == ["🚀"], "case does not matter")
        suite.expect(top("pizza") == ["🍕"], "pizza")
        suite.expect(top("🔥") == ["🔥"], "an emoji typed into the field finds itself")
        suite.expect(EmojiSearch.rank(records, query: "zzqqxx").isEmpty, "nonsense finds nothing")
        suite.expect(EmojiSearch.rank(records, query: "cat zzqq").isEmpty, "every word must match")
        suite.expect(EmojiSearch.rank(records, query: "   ").count == min(400, records.count),
                     "an empty query lists everything in order")
        let fixed = [record("🦁", "lion", keywords: ["cat"]), record("🐱", "cat face"), record("🐈", "cat"),
                     record("☕", "hot beverage", keywords: ["coffee"])]
        suite.expect(EmojiSearch.rank(fixed, query: "cat").map(\.emoji) == ["🐈", "🐱", "🦁"],
                     "the whole name, then a name word, then a keyword")
        let laugh = [record("🍭", "lollipop"), record("😂", "face with tears of joy", keywords: ["lol"])]
        suite.expect(EmojiSearch.rank(laugh, query: "lol").map(\.emoji) == ["😂", "🍭"],
                     "a keyword in full beats a name that only starts the same")
        suite.expect(EmojiSearch.rank(fixed, query: "café").isEmpty && EmojiSearch.fold("Café") == "cafe",
                     "accents fold away")
        var used = EmojiUsage()
        for _ in 0..<5 { used.record("☕") }
        suite.expect(EmojiSearch.rank(fixed, query: "coffee", usage: used).first?.emoji == "☕",
                     "usage lifts a match")
        let pair = [record("🐈", "cat", keywords: []), record("🐱", "cat face", keywords: [])]
        var often = EmojiUsage()
        for _ in 0..<50 { often.record("🐱") }
        suite.expect(EmojiSearch.rank(pair, query: "cat", usage: often).first?.emoji == "🐈",
                     "usage never lifts a weaker match past an exact name")
    }

    private static func tones(_ suite: TestSuite) {
        let wave = record("👋", "waving hand", tone: "👋🏻")
        suite.expect(wave.character(.none) == "👋" && wave.character(.medium) == "👋🏽" && wave.character(.dark) == "👋🏿",
                     "a tone fills the template")
        let pair = record("🧑‍🤝‍🧑", "people holding hands", tone: "🧑🏻‍🤝‍🧑🏻")
        suite.expect(pair.character(.mediumDark) == "🧑🏾‍🤝‍🧑🏾", "both people take the same tone")
        let smile = record("😀", "grinning face")
        suite.expect(smile.character(.dark) == "😀", "an emoji without a tone stays as it is")
        let bundledPair = bundled.first { $0.emoji == "🧑‍🤝‍🧑" }
        suite.expect(bundledPair?.character(.light) == "🧑🏻‍🤝‍🧑🏻", "the bundled template of people holding hands")
    }

    private static func usage(_ suite: TestSuite) {
        var usage = EmojiUsage()
        let start = Date(timeIntervalSince1970: 1_000_000)
        usage.record("😀", at: start)
        usage.record("🔥", at: start.addingTimeInterval(10))
        usage.record("😀", at: start.addingTimeInterval(20))
        usage.record("🚀", at: start.addingTimeInterval(30))
        suite.expect(usage.recent(10) == ["🚀", "😀", "🔥"], "recent: newest first")
        suite.expect(usage.recent(2) == ["🚀", "😀"] && usage.recent(0).isEmpty, "recent keeps its count")
        suite.expect(usage.frequent(10) == ["😀"], "frequently used: picked more than once")
        usage.record("🔥", at: start.addingTimeInterval(40))
        usage.record("🔥", at: start.addingTimeInterval(50))
        suite.expect(usage.frequent(10) == ["🔥", "😀"], "most picked first")
        suite.expect(usage.boost("🔥") > usage.boost("😀") && usage.boost("🌵") == 0 && usage.boost("🔥") <= 25,
                     "the search boost grows with use, capped")
        let restored = EmojiUsage(data: usage.data)
        suite.expect(restored == usage, "usage survives being stored")
        suite.expect(EmojiUsage(data: Data("x".utf8)).entries.isEmpty, "unreadable usage starts empty")
        var full = EmojiUsage()
        for index in 0..<(EmojiUsage.capacity + 10) {
            full.record("e\(index)", at: start.addingTimeInterval(Double(index)))
        }
        full.record("e0", at: start.addingTimeInterval(1000))
        suite.expect(full.entries.count == EmojiUsage.capacity && full.entries["e1"] == nil,
                     "past its capacity the least used and oldest go")
        usage.clear()
        suite.expect(usage.recent(10).isEmpty, "Clear forgets everything")
    }

    private static func sections(_ suite: TestSuite) {
        let records = [record("😀", "grinning face"), record("👋", "waving hand", category: .people),
                       record("🇮🇩", "flag: Indonesia", category: .flags)]
        let empty = EmojiPickerSections(records: records, usage: EmojiUsage(), recentCount: 16)
        suite.expect(empty.sections.map(\.id) == ["smileys", "people", "flags"],
                     "with nothing picked yet, the categories with emoji, in order")
        var usage = EmojiUsage()
        let now = Date(timeIntervalSince1970: 2_000_000)
        usage.record("👋", at: now)
        usage.record("👋", at: now.addingTimeInterval(1))
        usage.record("😀", at: now.addingTimeInterval(2))
        usage.record("🦄", at: now.addingTimeInterval(3)) // no longer on this Mac's list
        let full = EmojiPickerSections(records: records, usage: usage, recentCount: 16)
        suite.expect(full.sections.map(\.id) == ["recent", "frequent", "smileys", "people", "flags"],
                     "recent and frequently used lead: \(full.sections.map(\.id))")
        suite.expect(full.sections.first?.records.map(\.emoji) == ["😀", "👋"], "an emoji the list lacks is skipped")
        let none = EmojiPickerSections(records: records, usage: usage, recentCount: 0)
        suite.expect(none.sections.first?.id == "smileys", "a recent count of zero hides both rows")
        suite.expect(full.flat.count == 2 + 1 + 3, "the flat order runs through every section")
    }

    private static func navigation(_ suite: TestSuite) {
        typealias Nav = EmojiGridNavigation
        // Two sections of 5 and 3, four columns: rows 0..<4, 4..<5, 5..<8.
        let rows = Nav.rows(sectionCounts: [5, 3], columns: 4)
        suite.expect(rows == [0..<4, 4..<5, 5..<8], "each section starts a row: \(rows)")
        suite.expect(Nav.move(.right, from: 3, rows: rows) == 4 && Nav.move(.left, from: 0, rows: rows) == 0,
                     "left and right run through the order and stop at the ends")
        suite.expect(Nav.move(.down, from: 2, rows: rows) == 4, "down into a short row lands on its last emoji")
        suite.expect(Nav.move(.down, from: 4, rows: rows) == 5 && Nav.move(.up, from: 7, rows: rows) == 4,
                     "up and down keep the column where they can")
        suite.expect(Nav.move(.up, from: 1, rows: rows) == 1 && Nav.move(.down, from: 6, rows: rows) == 6,
                     "the first and last rows hold")
        suite.expect(Nav.move(.down, from: 0, rows: []) == 0 && Nav.rows(sectionCounts: [0, 2], columns: 0) == [0..<1, 1..<2],
                     "empty grids and a zero width are safe")
    }

    private static func preferences(_ suite: TestSuite) {
        let domain = "com.vorssaint.tests.emoji-picker"
        guard let defaults = UserDefaults(suiteName: domain) else { return suite.expect(false, "test defaults") }
        defaults.removePersistentDomain(forName: domain)
        defer { defaults.removePersistentDomain(forName: domain) }
        let fresh = EmojiPickerPreferences(defaults: defaults)
        suite.expect(!fresh.enabled && fresh.skinTone == .none && fresh.recentCount == 16 && fresh.showInCommandBar,
                     "off by default, yellow, 16 recent, in the Command Bar once on")
        defaults.set("mediumDark", forKey: EmojiPickerDefaults.skinTone)
        defaults.set(500, forKey: EmojiPickerDefaults.recentCount)
        let set = EmojiPickerPreferences(defaults: defaults)
        suite.expect(set.skinTone == .mediumDark && set.recentCount == 40, "the tone is read; the count is clamped")
        defaults.set("purple", forKey: EmojiPickerDefaults.skinTone)
        suite.expect(EmojiPickerPreferences(defaults: defaults).skinTone == .none, "an unknown tone reads as yellow")
        suite.expect(!EmojiPickerDefaults.backupKeys.contains(EmojiPickerDefaults.usage)
                        && EmojiPickerDefaults.backupKeys.allSatisfy { $0.hasPrefix("zenithEmojiPicker") },
                     "the backup carries the preferences, never what was picked")
    }
}
