"""Rebuild the Emoji Picker's bundled list from Unicode's own data.

Three files from Unicode, Inc. (Unicode License v3, see
Resources/Emoji/NOTICE.txt), fetched once at development time:

  emoji-test.txt                 https://unicode.org/Public/emoji/latest/emoji-test.txt
  annotations/en.xml             https://github.com/unicode-org/cldr  common/annotations/en.xml
  annotationsDerived/en.xml      https://github.com/unicode-org/cldr  common/annotationsDerived/en.xml

emoji-test.txt gives every fully-qualified emoji, its group, its name and
the Emoji version it arrived in. The CLDR annotations give the keywords
people search with ("haha", "lol"). Skin-tone variants are left out of the
list: the picker applies the person's tone at run time, from a template
kept beside each emoji that takes one (the light-tone sequence, every U+1F3FB
standing for the chosen tone). Emoji images are never shipped: the Mac's own
font draws them.

One line per emoji, tab-separated:

    group  emoji  name  keyword|keyword|…  version  tone-template

Run, then commit Resources/Emoji/emoji.tsv:

    python3 Tools/zenith-emoji-data.py emoji-test.txt en.xml en-derived.xml Resources/Emoji/emoji.tsv
"""
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

# emoji-test.txt's groups -> the picker's category ids. Component (the bare
# skin tones and hair styles) is not offered on its own.
GROUPS = {
    "Smileys & Emotion": "smileys",
    "People & Body": "people",
    "Animals & Nature": "animals",
    "Food & Drink": "food",
    "Travel & Places": "travel",
    "Activities": "activities",
    "Objects": "objects",
    "Symbols": "symbols",
    "Flags": "flags",
}
TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
LIGHT = 0x1F3FB
SELECTORS = {0xFE0F, 0xFE0E}
LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E(\d+\.\d+)\s+(.+)$")


def annotations(path):
    """cp (without FE0F) -> (keywords, tts name)."""
    keywords, names = {}, {}
    root = ET.parse(path).getroot()
    for node in root.iter("annotation"):
        cp = node.get("cp", "").replace("️", "")
        text = (node.text or "").strip()
        if node.get("type") == "tts":
            names[cp] = text
        else:
            keywords[cp] = [word.strip() for word in text.split("|") if word.strip()]
    return keywords, names


def clean(text):
    return " ".join(text.replace("\t", " ").split())


def main(argv):
    if len(argv) != 5:
        print(__doc__)
        return 2
    test_path, annotations_path, derived_path, out_path = map(Path, argv[1:])
    base_keywords, _ = annotations(annotations_path)
    derived_keywords, _ = annotations(derived_path)

    group = None
    entries = []          # (group, emoji, name, version, key)
    templates = {}        # base key (no tones, no selectors) -> light-tone sequence
    for raw in test_path.read_text(encoding="utf-8").splitlines():
        if raw.startswith("# group:"):
            group = GROUPS.get(raw.split(":", 1)[1].strip())
            continue
        match = LINE.match(raw)
        if not match or group is None:
            continue
        points = [int(part, 16) for part in match.group(1).split()]
        emoji = "".join(chr(point) for point in points)
        key = "".join(chr(point) for point in points if point not in TONES and point not in SELECTORS)
        tones = [point for point in points if point in TONES]
        if tones:
            # One tone throughout (the light one) is the template; mixed
            # tones, as in a couple of two people, are not offered.
            if all(point == LIGHT for point in tones) and key not in templates:
                templates[key] = emoji
            continue
        entries.append((group, emoji, clean(match.group(3)), match.group(2), key))

    lines = []
    for group, emoji, name, version, key in entries:
        lookup = emoji.replace("️", "")
        words = base_keywords.get(lookup) or derived_keywords.get(lookup) or []
        name_words = set(name.lower().replace(":", " ").split())
        kept = []
        for word in words:
            folded = clean(word).lower()
            if folded and folded != name.lower() and folded not in name_words and folded not in kept:
                kept.append(folded)
        lines.append("\t".join([group, emoji, name, "|".join(kept), version, templates.get(key, "")]))

    header = [
        "# Zenith Emoji Picker: generated by Tools/zenith-emoji-data.py. Do not edit.",
        "# From Unicode emoji-test.txt and CLDR annotations, (c) Unicode, Inc., Unicode License v3 (NOTICE.txt).",
        "# group\temoji\tname\tkeywords\tversion\ttone-template",
    ]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    toned = sum(1 for line in lines if not line.endswith("\t"))
    print(f"{len(lines)} emoji, {toned} take a skin tone, {out_path.stat().st_size // 1024} KB -> {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
